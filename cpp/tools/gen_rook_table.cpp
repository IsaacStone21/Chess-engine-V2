//writes cpp/engine/generated/rook_attacks.h: the fancy magic rook attack table, built with the engine's own masks,
//magics, shifts and offsets (magic.cpp is compiled into this tool), as a const array the Teensy keeps in flash.
//
//  gen_rook_table <output path>
//
//The CMake target regen_rook_table runs it on the header in the source tree.

#include <stdio.h>

#include "magic.h"

static uint64_t table[Magic::rookTableSize];

int main(int argc, char** argv) {
    if(argc != 2) {
        fprintf(stderr, "usage: gen_rook_table <output path>\n");
        return 2;
    }

    Magic::init();
    Magic::buildRookTable(table);

    FILE* out = fopen(argv[1], "wb");
    if(out == nullptr) {
        fprintf(stderr, "can't open %s\n", argv[1]);
        return 1;
    }

    fprintf(out, "//generated by cpp/tools/gen_rook_table from the masks and magics in magic.cpp; don't edit by hand.\n");
    fprintf(out, "//rook attacks indexed by Magic::rookIndex(square, occupied); ENGINE_FLASH keeps it in flash on the Teensy\n");
    fprintf(out, "#pragma once\n\n");
    fprintf(out, "#include <stdint.h>\n\n");
    fprintf(out, "#include \"../config.h\"\n\n");
    fprintf(out, "namespace Magic {\n\n");
    fprintf(out, "extern const uint64_t generatedRookAttacks[%d];\n\n", Magic::rookTableSize);
    fprintf(out, "ENGINE_FLASH const uint64_t generatedRookAttacks[%d] = {\n", Magic::rookTableSize);
    for(int index = 0; index < Magic::rookTableSize; index++) {
        fprintf(out, "%s0x%llxULL,%s", index % 8 == 0 ? "    " : "", (unsigned long long) table[index],
                index % 8 == 7 ? "\n" : " ");
    }
    fprintf(out, "};\n\n}\n");

    if(fclose(out) != 0) {
        fprintf(stderr, "error writing %s\n", argv[1]);
        return 1;
    }
    printf("wrote %d rook attack sets to %s\n", Magic::rookTableSize, argv[1]);
    return 0;
}
